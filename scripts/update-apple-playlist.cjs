const { writeFileSync } = require('node:fs');
const { resolve } = require('node:path');

const PLAYLIST_ID = 'pl.u-Zmblxd1CVM8G4d6';
const PLAYLIST_URL = `https://music.apple.com/cn/playlist/${PLAYLIST_ID}`;
const OUTPUT_FILE = resolve(__dirname, '..', 'features', 'music', 'music-apple-data.js');
const LOOKUP_BATCH_SIZE = 150;

const headers = {
  'user-agent': 'Mozilla/5.0 (PufferWork private playlist snapshot)',
  'accept-language': 'zh-CN,zh;q=0.9,en;q=0.8'
};

function decodeScriptJson(value) {
  const raw = String(value || '').trim();
  try { return JSON.parse(raw); } catch (_) {}
  const decoded = raw
    .replace(/&quot;/g, '"')
    .replace(/&#34;/g, '"')
    .replace(/&#x27;|&#39;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&');
  return JSON.parse(decoded);
}

function safeText(value, field, id) {
  const text = String(value || '').trim();
  if (!text) throw new Error(`Song ${id} has no ${field}`);
  return text;
}

function chunks(values, size) {
  const result = [];
  for (let index = 0; index < values.length; index += size) result.push(values.slice(index, index + size));
  return result;
}

async function lookupCatalogMetadata(ids) {
  const metadataById = new Map();
  for (const batch of chunks(ids, LOOKUP_BATCH_SIZE)) {
    const url = `https://itunes.apple.com/lookup?id=${batch.map(encodeURIComponent).join(',')}&country=cn`;
    const response = await fetch(url, { headers });
    if (!response.ok) throw new Error(`Apple catalog lookup failed: ${response.status}`);
    const body = await response.json();
    for (const item of body.results || []) {
      const id = String(item.trackId || '').trim();
      if (!id) continue;
      metadataById.set(id, {
        genre: String(item.primaryGenreName || '').trim(),
        releaseYear: /^\d{4}/.test(String(item.releaseDate || '')) ? Number(String(item.releaseDate).slice(0, 4)) : 0
      });
    }
  }
  return metadataById;
}

function playlistPage(root) {
  const entry = Array.isArray(root?.data) ? root.data[0] : null;
  if (!entry?.data || !Array.isArray(entry.data.sections)) {
    throw new Error('Apple Music page has no readable sections');
  }
  return entry.data;
}

function playlistHeader(page) {
  for (const section of page.sections) {
    for (const item of section?.items || []) {
      if (item?.contentDescriptor?.kind !== 'playlist') continue;
      if (item.contentDescriptor.identifiers?.storeAdamID !== PLAYLIST_ID) continue;
      if (Number(item.trackCount) > 0) return item;
    }
  }
  throw new Error('Apple Music page has no playlist header metadata');
}

function playlistTracks(page) {
  const section = page.sections.find(item =>
    item?.containerContentDescriptor?.kind === 'playlist' &&
    item.containerContentDescriptor.identifiers?.storeAdamID === PLAYLIST_ID &&
    Array.isArray(item.items) &&
    item.items.some(track => ['song', 'musicVideo'].includes(track?.contentDescriptor?.kind))
  );
  if (!section) throw new Error('Apple Music page has no track list');
  return section.items.map(item => {
    const descriptor = item?.contentDescriptor;
    const id = String(descriptor?.identifiers?.storeAdamID || '').trim();
    const url = String(descriptor?.url || '').trim();
    if (!['song', 'musicVideo'].includes(descriptor?.kind) || !id) throw new Error('Apple Music track has no playable ID');
    if (!/^https:\/\/music\.apple\.com\/cn\//.test(url)) throw new Error(`Song ${id} has no direct Apple Music URL`);
    return {
      id,
      title: safeText(item.title, 'title', id),
      artist: safeText(item.artistName || item.subtitleLinks?.map(link => link?.title).filter(Boolean).join(' / '), 'artist', id),
      url
    };
  });
}

function renderSnapshot(metadata, tracks) {
  const rows = tracks.map(track => `    ${JSON.stringify([track.id, track.title, track.artist, track.url, track.genre, track.releaseYear])}`).join(',\n');
  const catalogMetadataCount = tracks.filter(track => track.genre).length;
  return `// Generated by scripts/update-apple-playlist.cjs. Do not edit track rows by hand.\n` +
    `(function () {\n` +
    `  'use strict';\n\n` +
    `  window.PufferApplePlaylistData = Object.freeze({\n` +
    `    playlistId: ${JSON.stringify(PLAYLIST_ID)},\n` +
    `    playlistName: ${JSON.stringify(String(metadata.title || 'Apple Music 歌单'))},\n` +
    `    playlistUrl: ${JSON.stringify(PLAYLIST_URL)},\n` +
    `    trackCount: ${tracks.length},\n` +
    `    catalogMetadataCount: ${catalogMetadataCount},\n` +
    `    tracks: [\n${rows}\n    ]\n` +
    `  });\n` +
    `})();\n`;
}

async function main() {
  const response = await fetch(PLAYLIST_URL, { headers });
  if (!response.ok) throw new Error(`Apple Music request failed: ${response.status}`);
  const html = await response.text();
  const match = html.match(/<script[^>]*id=["']serialized-server-data["'][^>]*>([\s\S]*?)<\/script>/i);
  if (!match) throw new Error('Apple Music page has no serialized server data');

  const page = playlistPage(decodeScriptJson(match[1]));
  const metadata = playlistHeader(page);
  const tracks = playlistTracks(page);
  const ids = tracks.map(track => track.id);
  if (new Set(ids).size !== ids.length) throw new Error('Apple Music playlist contains duplicate song IDs');
  if (tracks.length !== Number(metadata.trackCount)) {
    throw new Error(`Apple Music returned ${tracks.length} tracks, expected ${metadata.trackCount}`);
  }

  const metadataById = await lookupCatalogMetadata(ids);
  tracks.forEach(track => Object.assign(track, metadataById.get(track.id) || { genre:'', releaseYear:0 }));

  writeFileSync(OUTPUT_FILE, renderSnapshot(metadata, tracks), 'utf8');
  process.stdout.write(`Saved ${tracks.length} tracks from "${metadata.title}" to ${OUTPUT_FILE}\n`);
}

main().catch(error => {
  process.stderr.write(`${error.stack || error.message}\n`);
  process.exitCode = 1;
});
