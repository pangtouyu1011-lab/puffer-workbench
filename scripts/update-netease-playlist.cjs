const { writeFileSync } = require('node:fs');
const { resolve } = require('node:path');

const PLAYLIST_ID = '162638755';
const PLAYLIST_URL = `https://music.163.com/playlist?id=${PLAYLIST_ID}`;
const DETAIL_URL = `https://music.163.com/api/v6/playlist/detail?id=${PLAYLIST_ID}`;
const SONG_DETAIL_URL = 'https://music.163.com/api/song/detail?ids=';
const OUTPUT_FILE = resolve(__dirname, '..', 'features', 'music', 'music-netease-data.js');
const BATCH_SIZE = 150;

const headers = {
  'user-agent': 'Mozilla/5.0 (PufferWork private playlist snapshot)',
  referer: 'https://music.163.com/'
};

async function readJson(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`NetEase request failed: ${response.status} ${url}`);
  const body = await response.json();
  if (body.code !== 200) throw new Error(`NetEase returned code ${body.code} for ${url}`);
  return body;
}

function chunks(values, size) {
  const result = [];
  for (let index = 0; index < values.length; index += size) result.push(values.slice(index, index + size));
  return result;
}

function songArtist(song) {
  const artists = Array.isArray(song.artists) ? song.artists : (Array.isArray(song.ar) ? song.ar : []);
  return artists.map(artist => String(artist && artist.name || '').trim()).filter(Boolean).join(' / ');
}

function safeText(value, field, id) {
  const text = String(value || '').trim();
  if (!text) throw new Error(`Song ${id} has no ${field}`);
  return text;
}

function renderSnapshot(metadata, tracks) {
  const rows = tracks.map(track => `    ${JSON.stringify([track.id, track.title, track.artist])}`).join(',\n');
  const updatedAt = Number(metadata.updateTime) || 0;
  return `// Generated by scripts/update-netease-playlist.cjs. Do not edit track rows by hand.\n` +
    `(function () {\n` +
    `  'use strict';\n\n` +
    `  window.PufferNeteasePlaylistData = Object.freeze({\n` +
    `    playlistId: ${JSON.stringify(PLAYLIST_ID)},\n` +
    `    playlistName: ${JSON.stringify(String(metadata.name || '网易云歌单'))},\n` +
    `    playlistUrl: ${JSON.stringify(PLAYLIST_URL)},\n` +
    `    updatedAt: ${updatedAt},\n` +
    `    trackCount: ${tracks.length},\n` +
    `    tracks: [\n${rows}\n    ]\n` +
    `  });\n` +
    `})();\n`;
}

async function main() {
  const detail = await readJson(DETAIL_URL);
  const playlist = detail.playlist;
  if (!playlist || !Array.isArray(playlist.trackIds)) throw new Error('Playlist metadata has no trackIds');

  const orderedIds = playlist.trackIds.map(item => String(item && item.id || '')).filter(Boolean);
  if (!orderedIds.length) throw new Error('Playlist contains no readable track IDs');
  if (new Set(orderedIds).size !== orderedIds.length) throw new Error('Playlist contains duplicate track IDs');

  const songsById = new Map();
  for (const batch of chunks(orderedIds, BATCH_SIZE)) {
    const ids = encodeURIComponent(JSON.stringify(batch.map(Number)));
    const response = await readJson(SONG_DETAIL_URL + ids);
    for (const song of response.songs || []) songsById.set(String(song.id), song);
  }

  const missingIds = orderedIds.filter(id => !songsById.has(id));
  if (missingIds.length) throw new Error(`Missing metadata for ${missingIds.length} tracks: ${missingIds.slice(0, 10).join(', ')}`);

  const tracks = orderedIds.map(id => {
    const song = songsById.get(id);
    return {
      id,
      title: safeText(song.name, 'title', id),
      artist: safeText(songArtist(song), 'artist', id)
    };
  });

  writeFileSync(OUTPUT_FILE, renderSnapshot(playlist, tracks), 'utf8');
  process.stdout.write(`Saved ${tracks.length} tracks from "${playlist.name}" to ${OUTPUT_FILE}\n`);
}

main().catch(error => {
  process.stderr.write(`${error.stack || error.message}\n`);
  process.exitCode = 1;
});
